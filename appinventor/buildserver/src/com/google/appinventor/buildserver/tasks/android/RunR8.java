package com.google.appinventor.buildserver.tasks.android;

import com.google.appinventor.buildserver.TaskResult;
import com.google.appinventor.buildserver.context.AndroidCompilerContext;
import com.google.appinventor.buildserver.context.AndroidPaths;
import com.google.appinventor.buildserver.interfaces.AndroidTask;
import com.google.appinventor.buildserver.interfaces.BuildType;
import com.google.appinventor.buildserver.util.AARLibrary;
import com.google.appinventor.buildserver.util.Execution;
import com.google.appinventor.buildserver.util.ExecutorUtils;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * Shrinks, optimizes and obfuscates the app's code with R8 and writes the dex files. Used in
 * place of {@link RunD8} for App Bundles when the buildserver runs with --enable-r8.
 *
 * <p>Unlike D8, R8 needs the whole program as class files, so the pre-dex cache is not used.
 *
 * <p>App Inventor calls component properties, methods and events by name at runtime (through
 * Kawa), so the keep rules here preserve those entry points. Everything else, including
 * components the project does not use, may be removed or renamed.
 */
@BuildType(aab = true)
public class RunR8 extends DexTask implements AndroidTask {
  private static final String ANNOTATIONS = "com.google.appinventor.components.annotations.";
  private static final String RUNTIME = "com.google.appinventor.components.runtime.";

  /** Keep rules generated by aapt2 for classes named in the manifest and layouts. */
  static File getAaptRulesFile(AndroidPaths paths) {
    return new File(paths.getBuildDir(), "aapt_rules.txt");
  }

  /** The obfuscation mapping written by R8; RunBundletool embeds it when present. */
  static File getMappingFile(AndroidPaths paths) {
    return new File(paths.getBuildDir(), "proguard.map");
  }

  /**
   * Build metadata written by R8 (r8.json). Google Play reads the obfuscation, optimization and
   * shrinking percentages from it; RunBundletool embeds it when present.
   */
  static File getBuildMetadataFile(AndroidPaths paths) {
    return new File(paths.getBuildDir(), "r8.json");
  }

  @Override
  public TaskResult execute(AndroidCompilerContext context) {
    try {
      Set<File> inputs = collectInputs(context);
      List<File> configs = new ArrayList<>();
      configs.add(writeKeepRules(context));
      File aaptRules = getAaptRulesFile(context.getPaths());
      if (aaptRules.isFile()) {
        configs.add(aaptRules);
      }
      for (AARLibrary aar : context.getComponentInfo().getExplodedAarLibs()) {
        File rules = new File(aar.getDirectory(), "proguard.txt");
        if (rules.isFile()) {
          configs.add(rules);
        }
      }

      if (!runR8(context, inputs, configs)) {
        return TaskResult.generateError("R8 failed.");
      }

      File[] files = context.getPaths().getTmpDir().listFiles((dir, name) -> name.endsWith(".dex"));
      if (files == null || files.length == 0) {
        return TaskResult.generateError("R8 produced no dex files.");
      }
      for (File f : files) {
        context.getResources().getDexFiles().add(f);
      }
      return TaskResult.generateSuccess();
    } catch (IOException e) {
      return TaskResult.generateError(e);
    }
  }

  /** Collects the same program inputs as RunD8, as class jars instead of pre-dexed files. */
  private static Set<File> collectInputs(AndroidCompilerContext context) throws IOException {
    Set<File> inputs = new LinkedHashSet<>();
    // R8 takes class files, not directories.
    try (Stream<Path> classes = Files.walk(context.getPaths().getClassesDir().toPath())) {
      classes.filter(p -> p.toString().endsWith(".class")).forEach(p -> inputs.add(p.toFile()));
    }
    inputs.add(new File(context.getResources().getSimpleAndroidRuntimeJar()));
    inputs.add(new File(context.getResources().getKawaRuntime()));
    if (context.isForCompanion()) {
      inputs.add(new File(context.getResources().getAcraRuntime()));
    }
    for (String jar : getCriticalJars(context)) {
      inputs.add(new File(context.getResource(jar)));
    }
    for (String jar : context.getResources().getSupportJars()) {
      inputs.add(new File(context.getResource(jar)));
    }
    for (String lib : context.getComponentInfo().getUniqueLibsNeeded()) {
      inputs.add(new File(lib));
    }
    for (String type : context.getExtCompTypes()) {
      inputs.add(new File(ExecutorUtils.getExtCompDirPath(type, context.getProject(),
          context.getExtTypePathCache())
          + context.getResources().getSimpleAndroidRuntimeJarPath()));
    }
    return inputs;
  }

  private static File writeKeepRules(AndroidCompilerContext context) throws IOException {
    File rules = new File(context.getPaths().getBuildDir(), "appinventor_rules.pro");
    try (PrintStream out = new PrintStream(new FileOutputStream(rules))) {
      // Kawa's desktop REPL and GUI, never loaded on Android.
      out.println("-dontwarn java.awt.**");
      out.println("-dontwarn javax.swing.**");
      out.println("-dontwarn javax.imageio.**");
      // Annotation-only dependencies of Guava, OpenCensus and others.
      out.println("-dontwarn javax.annotation.**");
      out.println("-dontwarn org.checkerframework.**");
      out.println("-dontwarn com.google.errorprone.annotations.**");
      out.println("-dontwarn androidx.annotation.**");
      out.println("-dontwarn android.support.annotation.**");
      // httpmime wants a newer httpcore than the device's org.apache.http.legacy. Those paths
      // fail the same way in D8 builds.
      out.println("-dontwarn org.apache.http.util.Args");
      out.println("-dontwarn org.apache.http.entity.ContentType");
      out.println("-dontwarn org.apache.http.Consts");
      // AndroidRuntime.jar refers to libraries that are added only for the Companion (WebRTC,
      // ACRA) or only for components that need them (repackaged org.json).
      out.println("-dontwarn org.webrtc.**");
      out.println("-dontwarn org.acra.**");
      out.println("-dontwarn " + RUNTIME + "repackaged.**");
      // Extensions and libraries may reference optional classes we can't foresee. R8 still logs
      // each one as "Warning: Missing class ...", but doesn't fail the build, just as D8 doesn't.
      out.println("-ignorewarnings");
      out.println("-keepattributes *Annotation*,Signature,InnerClasses,EnclosingMethod,"
          + "Exceptions,SourceFile,LineNumberTable");
      out.println("-renamesourcefileattribute SourceFile");

      // Kawa looks up classes and members by name throughout its runtime.
      out.println("-keep class gnu.** { *; }");
      out.println("-keep class kawa.** { *; }");
      // The compiled runtime.scm, loaded by name when a screen starts.
      out.println("-keep class com.google.youngandroid.** { *; }");

      // The compiled screens (YAIL), which Kawa links against by name.
      String mainClass = context.getProject().getMainClass();
      String pkg = mainClass.substring(0, mainClass.lastIndexOf('.'));
      out.println("-keep class " + pkg + ".** { *; }");

      // Runtime classes that runtime.scm and generated YAIL reference by name.
      out.println("-keep class " + RUNTIME + "Form { *; }");
      out.println("-keep class " + RUNTIME + "AppInventorCompatActivity { *; }");
      out.println("-keep class " + RUNTIME + "Component { *; }");
      out.println("-keep class " + RUNTIME + "ComponentContainer { *; }");
      out.println("-keep class " + RUNTIME + "AndroidViewComponent { *; }");
      out.println("-keep class " + RUNTIME + "EventDispatcher { *; }");
      out.println("-keep class " + RUNTIME + "HandlesEventDispatching { *; }");
      out.println("-keep class " + RUNTIME + "OptionHelper { *; }");
      // Compiled apps never evaluate YAIL at runtime, so R8 may drop the util, errors and common
      // classes they don't use (allowshrinking); the ones they use keep their names and members.
      // The same goes for the Companion-only ReplForm and ReplApplication. The Companion's REPL
      // can reach any of them, so it keeps them all.
      String keepRuntime = context.isForCompanion() ? "-keep class " : "-keep,allowshrinking class ";
      out.println(keepRuntime + RUNTIME + "ReplForm { *; }");
      out.println(keepRuntime + RUNTIME + "ReplApplication { *; }");
      out.println(keepRuntime + RUNTIME + "util.** { *; }");
      out.println(keepRuntime + RUNTIME + "errors.** { *; }");
      out.println(keepRuntime + "com.google.appinventor.components.common.** { *; }");

      // Components the project uses. Unused components may be removed.
      Set<String> types = new TreeSet<>(context.getSimpleCompTypes());
      for (String type : types) {
        out.println("-keep class " + type + " { public <init>(...); }");
      }
      // Extensions may use reflection we cannot see, so keep their packages whole.
      Set<String> extPackages = new TreeSet<>();
      for (String type : context.getExtCompTypes()) {
        extPackages.add(type.substring(0, type.lastIndexOf('.')));
      }
      for (String extPkg : extPackages) {
        out.println("-keep class " + extPkg + ".** { *; }");
      }

      // Blocks call properties, methods and events by name, including inherited ones.
      out.println("-keepclassmembers class * {");
      out.println("  @" + ANNOTATIONS + "SimpleProperty *;");
      out.println("  @" + ANNOTATIONS + "SimpleFunction *;");
      out.println("  @" + ANNOTATIONS + "SimpleEvent *;");
      out.println("  @" + ANNOTATIONS + "DesignerProperty *;");
      // Looked up by name in PropertyUtil.copyComponentProperties.
      out.println("  @" + ANNOTATIONS + "SimplePropertyCopier *;");
      out.println("}");
      // Form.callInitialize looks up Initialize() by name; Sprite and others rely on it.
      out.println("-keepclassmembers class * implements " + RUNTIME + "Component {");
      out.println("  public void Initialize();");
      out.println("}");

      // Standard Android rules (as in proguard-android-optimize.txt).
      out.println("-keepclasseswithmembernames class * { native <methods>; }");
      out.println("-keepclassmembers enum * { public static **[] values(); "
          + "public static ** valueOf(java.lang.String); }");
      out.println("-keepclassmembers class * implements android.os.Parcelable { "
          + "public static final ** CREATOR; }");
      out.println("-keepclassmembers class * implements java.io.Serializable { "
          + "static final long serialVersionUID; private static final java.io.ObjectStreamField[] "
          + "serialPersistentFields; private void writeObject(java.io.ObjectOutputStream); "
          + "private void readObject(java.io.ObjectInputStream); java.lang.Object writeReplace(); "
          + "java.lang.Object readResolve(); }");
      out.println("-keepclassmembers class * { @android.webkit.JavascriptInterface <methods>; }");
      out.println("-keepclassmembers class **.R$* { public static <fields>; }");
    }
    return rules;
  }

  private static boolean runR8(AndroidCompilerContext context, Set<File> inputs,
      List<File> configs) throws IOException {
    // Same main dex seeds as RunD8, needed when minSdk < 21.
    Set<String> mainDexClasses = new TreeSet<>();
    mainDexClasses.add(RUNTIME + "*");
    mainDexClasses.add(RUNTIME + "**.*");
    mainDexClasses.add("kawa.**.*");
    mainDexClasses.add("androidx.core.content.FileProvider");
    mainDexClasses.add("androidx.appcompat.**.*");
    mainDexClasses.add("androidx.collection.*");
    mainDexClasses.add("androidx.vectordrawable.**.*");
    mainDexClasses.add(context.getProject().getMainClass());

    List<String> args = new ArrayList<>();
    args.add("-Xmx" + context.getChildProcessRam() + "M");
    args.add("-Xss8m");
    // R8 runs in a short-lived JVM, where C2 compilation costs more than it saves. C1 only
    // makes the R8 step 25-47% faster; R8's output doesn't depend on the JIT.
    args.add("-XX:TieredStopAtLevel=1");
    args.add("-cp");
    args.add(context.getResources().getD8Jar());
    args.add("com.android.tools.r8.R8");
    args.add("--release");
    args.add("--dex");
    args.add("--lib");
    args.add(context.getResources().getAndroidRuntime());
    // Provided on the device via <uses-library org.apache.http.legacy> (see CreateManifest).
    args.add("--lib");
    args.add(context.getResources().getApacheHttpLegacyJar());
    args.add("--output");
    args.add(context.getPaths().getTmpDir().getAbsolutePath());
    args.add("--min-api");
    args.add(Integer.toString(AndroidBuildUtils.computeMinSdk(context)));
    args.add("--main-dex-rules");
    args.add(writeClassRules(context.getPaths().getClassesDir(), mainDexClasses));
    args.add("--pg-map-output");
    args.add(getMappingFile(context.getPaths()).getAbsolutePath());
    args.add("--build-metadata-output");
    args.add(getBuildMetadataFile(context.getPaths()).getAbsolutePath());
    for (File config : configs) {
      args.add("--pg-conf");
      args.add(config.getAbsolutePath());
    }
    for (File input : inputs) {
      args.add(input.getAbsolutePath());
    }

    File argsFile = new File(context.getPaths().getTmpDir(), "r8arguments.txt");
    try (PrintStream ps = new PrintStream(new FileOutputStream(argsFile))) {
      for (String arg : args) {
        ps.println(arg);
      }
    }
    String[] command = {"java", "@" + argsFile.getAbsolutePath()};
    context.getReporter().info("Running R8");
    synchronized (context.getResources().getSyncKawaOrDx()) {
      return Execution.execute(context.getPaths().getTmpDir(), command, System.out, System.err,
          Execution.Timeout.LONG);
    }
  }
}
